-- Devoluções de venda (entradas) do Protheus -> raw.devolucoes
-- Grão: item de NF de devolução (SD1010).
-- Espelho fiel da query da fFaturamento.xlsx (aba fDevoluções): a conversão
-- caixa->quilo (-CX) fica EMBUTIDA aqui, pois cada fato do Excel tem sua
-- própria lista de -CX (necessário para reconciliar 1:1 com a planilha).
SELECT
    SD1.D1_FILIAL AS FILIAL,
    SD1.D1_ITEM   AS ITEM,
    SD1.D1_DOC    AS NF,
    CASE
        WHEN SD1.D1_COD = 'PA01010001-CX' THEN 'PA01010001'
        WHEN SD1.D1_COD = 'PA01020010-CX' THEN 'PA01020010'
        WHEN SD1.D1_COD = 'PA01020012-CX' THEN 'PA01020012'
        WHEN SD1.D1_COD = 'PA01020021-CX' THEN 'PA01020021'
        WHEN SD1.D1_COD = 'PA01010005-CX' THEN 'PA01010005'
        WHEN SD1.D1_COD = 'PA01010006-CX' THEN 'PA01010006'
        WHEN SD1.D1_COD = 'PA01010011-CX' THEN 'PA01010011'
        ELSE SD1.D1_COD
    END AS CODPROD,
    CASE
        WHEN SD1.D1_COD IN ('PA01010001-CX','PA01020010-CX','PA01020012-CX','PA01020021-CX','PA01010005-CX','PA01010006-CX','PA01010011-CX') THEN 'KG'
        ELSE SD1.D1_UM
    END AS UM,
    CASE
        WHEN SD1.D1_COD = 'PA01010001-CX' THEN SD1.D1_QUANT * 10
        WHEN SD1.D1_COD = 'PA01020010-CX' THEN SD1.D1_QUANT * 2.016
        WHEN SD1.D1_COD = 'PA01020012-CX' THEN SD1.D1_QUANT * 4
        WHEN SD1.D1_COD = 'PA01020021-CX' THEN SD1.D1_QUANT * 2.016
        WHEN SD1.D1_COD = 'PA01010005-CX' THEN SD1.D1_QUANT * 10
        WHEN SD1.D1_COD = 'PA01010006-CX' THEN SD1.D1_QUANT * 9.6
        WHEN SD1.D1_COD = 'PA01010011-CX' THEN SD1.D1_QUANT * 10
        ELSE SD1.D1_QUANT
    END AS QTD,
    CASE
        WHEN SD1.D1_COD = 'PA01010001-CX' THEN SD1.D1_VUNIT / 10
        WHEN SD1.D1_COD = 'PA01020010-CX' THEN SD1.D1_VUNIT / 2.016
        WHEN SD1.D1_COD = 'PA01020012-CX' THEN SD1.D1_VUNIT / 4
        WHEN SD1.D1_COD = 'PA01020021-CX' THEN SD1.D1_VUNIT / 2.016
        WHEN SD1.D1_COD = 'PA01010005-CX' THEN SD1.D1_VUNIT / 10
        WHEN SD1.D1_COD = 'PA01010006-CX' THEN SD1.D1_VUNIT / 9.6
        WHEN SD1.D1_COD = 'PA01010011-CX' THEN SD1.D1_VUNIT / 10
        ELSE SD1.D1_VUNIT
    END AS VRUNIT,
    SD1.D1_TOTAL - SD1.D1_VALDESC AS VRTOTAL,
    CONVERT(VARCHAR, CONVERT(DATE, SF2.F2_EMISSAO, 103), 105) AS DTAEMISSNFORI,
    SD1.D1_ITEMORI AS ITEMORI,
    SD1.D1_NFORI   AS NFORIGEM,
    SD1.D1_FORNECE AS CLIENTE,
    SD1.D1_LOJA    AS LJCLI,
    SD1.D1_SERIE   AS SERIE,
    SD1.D1_COR     AS MOTIVODEV,
    SD1.D1_CHASSI  AS DESTINO,
    SF1.F1_FORMUL,
    CONVERT(VARCHAR, CONVERT(DATE, SD1.D1_EMISSAO, 103), 105) AS EMISSAO,
    CONVERT(VARCHAR, CONVERT(DATE, SD1.D1_DTDIGIT, 103), 105) AS LANCAMENTO
FROM SD1010 SD1
INNER JOIN SF1010 SF1 ON SF1.D_E_L_E_T_ = ''
    AND SF1.F1_FILIAL = SD1.D1_FILIAL
    AND SF1.F1_DOC = SD1.D1_DOC
    AND SF1.F1_SERIE = SD1.D1_SERIE
    AND SF1.F1_FORNECE = SD1.D1_FORNECE
    AND SF1.F1_LOJA = SD1.D1_LOJA
LEFT JOIN SF2010 SF2 ON SF2.D_E_L_E_T_ = ''
    AND SF2.F2_FILIAL = SD1.D1_FILIAL
    AND SF2.F2_DOC = SD1.D1_NFORI
WHERE SD1.D_E_L_E_T_ = ''
  AND (
        SD1.D1_CF IN ('1202','1203','1410','1411','1201','1903','2410','2411','2201','2202','2203','2911','2551')
     OR (SD1.D1_TIPO = 'D' AND SD1.D1_CF = '')
      )
  AND SD1.D1_COD LIKE '%PA%'
  AND (SD1.D1_FORNECE <> '97316293' AND SD1.D1_FORNECE <> '30704321')
  AND SD1.D1_SERIE NOT LIKE '%AC%'
  AND SF1.F1_STATUS <> ''
  AND (SD1.D1_FILIAL <> '01004' OR SD1.D1_DOC NOT IN ('000016378','000016379','000016380','000016621','000016622','000016623','000016625','000016626','000016696','000016714','000016715','000016915','000016916','000016917'))
  AND (SD1.D1_FILIAL <> '01006' OR SD1.D1_DOC NOT IN ('000045676','000045699'))
