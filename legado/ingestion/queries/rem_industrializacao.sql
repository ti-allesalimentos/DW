-- Remessa para industrialização do Protheus -> raw.rem_industrializacao
-- Grão: item de NF. Espelho fiel da fFaturamento.xlsx (aba fRemIndustrializacao).
-- CFOP 5901/5903/6901/6903. Conversão -CX embutida (só 2 códigos aqui).
SELECT
    SD2.D2_FILIAL AS FILIAL,
    SD2.D2_ITEM   AS ITEM,
    CASE
        WHEN SD2.D2_COD = 'PA01010001-CX' THEN 'PA01010001'
        WHEN SD2.D2_COD = 'PA01020010-CX' THEN 'PA01020010'
        ELSE SD2.D2_COD
    END AS CODPROD,
    CASE
        WHEN SD2.D2_COD = 'PA01010001-CX' THEN SD2.D2_QUANT * 10
        WHEN SD2.D2_COD = 'PA01020010-CX' THEN SD2.D2_QUANT * 2.016
        ELSE SD2.D2_QUANT
    END AS QTD,
    CASE
        WHEN SD2.D2_COD IN ('PA01010001-CX','PA01020010-CX') THEN 'KG'
        ELSE SD2.D2_UM
    END AS UM,
    CASE
        WHEN SD2.D2_COD = 'PA01010001-CX' THEN SD2.D2_PRCVEN / 10
        WHEN SD2.D2_COD = 'PA01020010-CX' THEN SD2.D2_PRCVEN / 2.016
        ELSE SD2.D2_PRCVEN
    END AS PRCUNIT,
    SD2.D2_TOTAL AS TOTAL,
    SD2.D2_CF AS CFOP,
    SD2.D2_CLIENTE AS CODCLI,
    SD2.D2_LOJA AS LJCLI,
    SD2.D2_DOC AS NFE,
    SD2.D2_SERIE AS _SERIE,
    CONVERT(VARCHAR, CONVERT(DATE, SD2.D2_EMISSAO, 103), 105) AS _DTEMISSAO,
    SF2.F2_COND AS _CONDPGTO,
    SC5.C5_TABELA AS TABPRECO,
    SF2.F2_DUPL AS _DUPLICATA,
    SF2.F2_EST AS _ESTADO,
    SF2.F2_TIPOCLI AS _TIPOCLI,
    SF2.F2_VEND1 AS _CODVEND,
    SF2.F2_VEND2 AS _CONDESPECIAL,
    SF2.F2_TIPO AS TIPO
FROM SD2010 SD2
LEFT JOIN SF2010 SF2
    ON SF2.D_E_L_E_T_ <> '*'
   AND SD2.D2_FILIAL = SF2.F2_FILIAL
   AND SD2.D2_DOC = SF2.F2_DOC
   AND SD2.D2_CLIENTE = SF2.F2_CLIENTE
   AND SD2.D2_LOJA = SF2.F2_LOJA
INNER JOIN SC5010 SC5
    ON SC5.D_E_L_E_T_ = ''
   AND SC5.C5_FILIAL = SD2.D2_FILIAL
   AND SC5.C5_NUM = SD2.D2_PEDIDO
WHERE
    SD2.D_E_L_E_T_ <> '*'
    AND (SF2.D_E_L_E_T_ <> '*' OR SF2.D_E_L_E_T_ IS NULL)
    AND SD2.D2_EMISSAO > '20250131'
    AND SD2.D2_CLIENTE <> '97316293'
    AND SD2.D2_CF IN ('5901', '5903', '6901', '6903')
    AND SD2.D2_FILIAL IN ('01001', '01003', '01004', '01005', '01006', '01007', '01009', '01010', '01011')
